HOOK_WHAT_NEVER_WORKS = """
BANNED HOOK PATTERNS — never use these:

- Introduction hooks: "Hi guys, so today I wanted to talk about..." — not a hook, it's a warm-up
- Listicles without original framing: "My favorite things to do in..." / "5 things I learned..."
- Flat observations: "Recovery is important because..." — no tension, no surprise
- Over-narrated setups: "Two years ago I quit drinking" then backstory — start at the climax
- Hooks that explain intention: "I want to share why I think..." — kills mystery
- Safe and generic: "I've been thinking about sobriety lately" — zero friction
- AI-sounding language: "In a world where authenticity matters..." — instant scroll
- Lacks specificity: "Life is hard sometimes" — rewrite as "I cried in a Tesco car park at 3pm on a Tuesday"
- The humble brag: "I never expected this many followers..." — audiences smell it
"""

HOOK_DEVICES = """
THE 9 DEVICES:

1. THE QUESTION — open cognitive loop the brain must resolve
Avoid yes/no. Force comparison. No single right answer = maximum introspection.
The viewer must resolve it — so they stay.
Examples: "Which Disney princess messed up millennial women the most?" /
"Was it worth it to be happy for a little bit even though it ended up sad?"
Template: "Which [specific category] [action] [specific group] the most?"

2. THE GUT-PUNCH — puncture a romantic ideal against harsh reality
Collide something people romanticize with reality. Lead with the emotional conclusion.
Leave space for the viewer to project their own experience.
Examples: "Everyone is an artist until the rent is due." /
"I don't know how to explain it but I feel like something special was stolen from me."
Template: "Everyone [subject] is [idealized thing] until [harsh reality]"

3. THE METAPHOR — bypass rational processing through association
Combine absurdity with vulnerability. Layer clauses. Anchor abstract in physical experience.
Examples: "Making friends in your mid twenties is like showing up to a sex party in crocs
and asking if there's a signup sheet."
Template: "[Complex experience] is like [absurdly specific scenario]"

4. THE CONFESSION — disarming through reciprocity
Flip the expected reaction. Bait-and-switch. Raw unadorned truth beats clever.
The "I've been pretending to [X] for [timeframe]" structure carries enormous weight.
Examples: "I've been pretending to like my life for two years." /
"I'm at the age where if I got a girl pregnant my mom wouldn't be disappointed but I would."
Template: "I've been pretending to [X] for [timeframe]" or "I'm at the age where [expected] but [honest]"

5. THE NARRATOR — signal that a story is coming
Universal experience so viewer feels seen before the point. Hyper-specific backstory = trust.
Past tense signals transformation is coming: "For the longest time I thought..."
Examples: "4 years ago I thought the meaning of life was getting a girlfriend. I was a
late-blooming 17 year old who spent his high school years watching anime and playing league."
Template: "For the longest time I thought [belief]..." / "One day, you realize [quiet revelation]"

6. THE DECLARATION — bold statement, total conviction
State as fact, not opinion. No "I think" or "maybe." Challenge a deeply held assumption.
You don't need to be right — you need to be convicted.
Lexi already uses this: "Most sober people I've met stay away from bars. I don't."
Template: "The biggest predictor of [outcome] isn't [conventional factor], it's [unexpected factor]"

7. THE PARADOX — instant tension from logical impossibility
Brain short-circuits trying to resolve it. Success = disappointment challenges the sold narrative.
Examples: "Getting everything I ever wanted has been a profoundly disappointing experience." /
"An entire generation is currently studying for jobs that won't exist, and taking on 6 figure debt."

8. THE PROPHECY — urgency + authority + FOMO
Promise transformation through one specific shift. Attack the dominant narrative.
Examples: "I stopped working on myself and it's the best thing I've ever done." /
"If you can master this one mindset shift you will be in the 1%."

9. THE CONTRARIAN — disrupt pattern recognition
Reframe the entire discourse in one sentence. Attack sacred advice everyone repeats.
Lexi's 775-like post IS this device: "Most sober people stay away from bars. I don't."
Template: "You don't hate [X]. What you hate is [reframe]." /
"[Sacred advice] is overrated. [Reframe]."
"""

HOOK_FRAMEWORKS_PROMPT = HOOK_WHAT_NEVER_WORKS + "\n" + HOOK_DEVICES
